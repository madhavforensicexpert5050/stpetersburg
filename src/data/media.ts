export type Rights = 'project-placeholder' | 'owner-licensed' | 'ai-generated';
export type Publication = 'placeholder-preview-only' | 'approved' | 'synthetic-preview-only';

export type Scene =
  | { kind: 'interior'; room: RoomId; style: StyleId; furnish: 'none' | 'old' | 'staged'; wall?: string; floor?: 'oak' | 'tile' | 'worn' | 'walnut' | 'stone'; ceiling?: 'plain' | 'beams' | 'wood'; dim?: boolean }
  | { kind: 'exterior'; color?: string; trim?: string; door?: string; yard?: 'bare' | 'planted'; time?: 'day' | 'dusk'; dim?: boolean };

export interface MediaItem {
  id: string;
  page: string;
  section: string;
  pair?: string;
  role?: 'before' | 'after' | 'single';
  src: string;
  width: number;
  height: number;
  aspect: string;
  alt: string;
  caption: string;
  label: string;
  source: string;
  rights: Rights;
  ownerApproved: boolean;
  publication: Publication;
  scene: Scene;
  responsive?: { src: string; width: number }[];
  /** What this exact image visibly shows (from image-notes.ts). Absent when no checked note matches the file. */
  description?: string;
}

const W = 1500, H = 1000;
/** Short, consistent wording for AI-created images. Licensed client photos keep their own captions. */
const finishAi = (m: MediaItem): MediaItem => (m.rights === 'ai-generated'
  ? { ...m, caption: `AI-created concept: ${m.label}.`, alt: m.alt.replace(/^AI-generated demonstration of /i, 'AI-created image of ') }
  : m);
const base = (id: string, page: string, section: string, label: string, alt: string, scene: Scene, extra: Partial<MediaItem> = {}): MediaItem => finishAi({
  id, page, section, label, alt, scene, caption: `Illustration: ${label}`,
  src: `/media/placeholders/${id}.svg`, width: W, height: H, aspect: '3:2',
  source: 'StageLiora project illustration (generated by scripts/generate-placeholders.mjs)',
  rights: 'project-placeholder', ownerApproved: false, publication: 'placeholder-preview-only', ...extra, ...(generatedMedia as Record<string, Partial<MediaItem>>)[id],
});

function pair(key: string, page: string, section: string, beforeLabel: string, afterLabel: string, beforeAlt: string, afterAlt: string, before: Scene, after: Scene): MediaItem[] {
  return [
    base(`${key}-before`, page, section, `Before — ${beforeLabel}`, beforeAlt, before, { pair: key, role: 'before' }),
    base(`${key}-after`, page, section, `After — ${afterLabel}`, afterAlt, after, { pair: key, role: 'after' }),
  ];
}

