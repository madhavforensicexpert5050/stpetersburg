// V24 Portfolio P1: adds the 13 production-QA-approved images (one room in eight styles, the sunroom pair and the
// screened-lanai pair) to generated-media.ts and provenance.json. Additive only: every existing entry, file and
// sha256 is left exactly as it is. Inputs are the private QA register and the manifest (docs/, never deployed).
// Owner approved publication of all 13 on 2026-11-12. A set is integrated only when every image in it is approved,
// so Section 3 (one before plus eight afters) is all-or-nothing.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { media } from '../src/data/media.ts';

const REGISTER = 'docs/p1-remaining-production-2026-11-12/qa-approval-register.json';
const MANIFEST = 'docs/portfolio-image-manifest.json';
const register = JSON.parse(fs.readFileSync(REGISTER, 'utf8'));
const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
const out = 'public/media/generated';
const genFile = 'src/data/generated-media.ts';
const provFile = path.join(out, 'provenance.json');

const genSrc = fs.readFileSync(genFile, 'utf8');
const generated = JSON.parse(genSrc.slice(genSrc.indexOf('= {') + 2).replace(/;\s*$/, ''));
const provenance = JSON.parse(fs.readFileSync(provFile, 'utf8'));
const pairOf = (id) => id.replace(/-(before|after|modern|contemporary|coastal|scandinavian|farmhouse|traditional|industrial|transitional)$/, '');

if (!register.allRequiredImagesQaApproved) throw Error('Register does not approve every required image.');
const sets = new Map();
for (const i of register.images) sets.set(pairOf(i.id), [...(sets.get(pairOf(i.id)) || []), i]);
let added = 0;
for (const [pair, items] of sets) {
  if (!items.every((i) => i.qaApproved && i.qa === 'accepted' && i.state === 'approved')) { console.log(`Skipped ${pair}: not every image is approved`); continue; }
  for (const i of items) {
    if (generated[i.id] || provenance.some((p) => p.id === i.id)) throw Error(`${i.id} is already integrated`);
    const slot = media.find((m) => m.id === i.id);
    if (!slot) throw Error(`Register the media slot for ${i.id} in src/data/media.ts first`);
    const meta = await sharp(i.path).metadata();
    if (!meta.width || Math.abs(meta.width / meta.height - 1.5) > 0.01) throw Error(`Unexpected aspect ratio: ${i.id}`);
    if (i.sha256 && crypto.createHash('sha256').update(fs.readFileSync(i.path)).digest('hex') !== i.sha256) throw Error(`Master differs from the QA register: ${i.id}`);
    const responsive = [];
    for (const width of [480, 900, 1500]) {
      const filename = width === 1500 ? i.filename : i.filename.replace('.webp', `-${width}w.webp`);
      const file = path.join(out, filename);
      if (fs.existsSync(file)) throw Error(`Refusing to overwrite ${file}`);
      await sharp(i.path).rotate().resize({ width, withoutEnlargement: true }).webp({ quality: 84, effort: 6 }).toFile(file);
      responsive.push({ src: `/media/generated/${filename}`, width });
    }
    const src = `/media/generated/${i.filename}`;
    const plan = manifest.p1.images.find((x) => x.id === i.id);
    const composite = Boolean(i.base);
    generated[i.id] = {
      src, width: 1500, height: 1000, alt: slot.alt, caption: `AI-created concept: ${slot.label}.`,
      source: composite ? `OpenAI image_gen furniture and decor composited onto the unchanged ${i.base}` : 'OpenAI image_gen; original synthetic scene',
      rights: 'ai-generated', ownerApproved: false, publication: 'synthetic-preview-only', responsive,
    };
    provenance.push({
      id: i.id, src, method: composite ? 'image_gen isolated furniture and decor, composited onto the exact before' : 'image_gen',
      base: i.base || null, pair, sha256: crypto.createHash('sha256').update(fs.readFileSync(path.join('public', src))).digest('hex'),
      // Before-only reviews were written before their afters passed; drop that now-outdated clause.
      visualReview: i.review.replace(/;\s*(no matching after is accepted|no staged pair accepted)\./, '.'),
      classification: 'Original AI-generated demonstration of a fictional property; not client work; preview use only. No claim of exclusive copyright or MLS acceptance.',
      prompt: i.prompt || plan?.prompt,
    });
    added++;
  }
}
fs.writeFileSync(genFile, `// Generated by scripts/integrate-generated-media.mjs from visually accepted receipts.\n// V24 P1 entries were appended by scripts/integrate-p1-media.mjs from the production QA register.\nimport type { MediaItem } from './media.ts';\nexport const generatedMedia: Record<string, Partial<MediaItem>> = ${JSON.stringify(generated, null, 2)};\n`);
fs.writeFileSync(provFile, JSON.stringify(provenance, null, 2) + '\n');
console.log(`Added ${added} images (${added * 3} WebP files). Existing entries unchanged.`);
