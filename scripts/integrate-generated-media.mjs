// Optimize only visually reviewed assets. Never integrate half of a comparison.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import sharp from 'sharp';
import { media } from '../src/data/media.ts';
const plan=JSON.parse(fs.readFileSync('docs/stageliora-image-production-plan.json','utf8'));
const receipts=JSON.parse(fs.readFileSync('docs/stageliora-generation-receipts.json','utf8'));
const out='public/media/generated'; fs.mkdirSync(out,{recursive:true});
const generated={}, provenance=[];
for(const p of plan) {
  const r=receipts[p.id];
  if(!r || r.qa!=='accepted') continue;
  if(p.pair && !['before','after'].every(role=>receipts[`${p.pair}-${role}`]?.qa==='accepted')) continue;
  const input=sharp(r.path); const meta=await input.metadata();
  if(!meta.width||!meta.height||Math.abs(meta.width/meta.height-1.5)>.01) throw Error(`Unexpected aspect ratio: ${p.id}`);
  const sizes=[480,900,1500], responsive=[];
  for(const width of sizes) {
    const filename=width===1500?p.filename:p.filename.replace('.webp',`-${width}w.webp`);
    await sharp(r.path).rotate().resize({width,withoutEnlargement:true}).webp({quality:84,effort:6}).toFile(path.join(out,filename));
    responsive.push({src:`/media/generated/${filename}`,width});
  }
  const original=media.find(m=>m.id===p.id);
  const alt=original.alt.replace(/^Illustration of /,'AI-generated demonstration of ');
  generated[p.id]={src:`/media/generated/${p.filename}`,width:1500,height:1000,alt,caption:`AI-generated demonstration: ${original.label}. Fictional property; not a completed client project.`,source:'OpenAI image_gen; original synthetic scene'+(r.base?`; edit of ${r.base}`:''),rights:'ai-generated',ownerApproved:false,publication:'synthetic-preview-only',responsive};
  provenance.push({id:p.id,src:generated[p.id].src,method:r.method,base:r.base||null,pair:p.pair||null,sha256:crypto.createHash('sha256').update(fs.readFileSync(path.join('public',generated[p.id].src))).digest('hex'),visualReview:r.review||'Reviewed in production session',classification:'Original AI-generated demonstration of a fictional property; not client work; preview use only. No claim of exclusive copyright or MLS acceptance.',prompt:r.prompt||p.prompt});
}
fs.writeFileSync('src/data/generated-media.ts',`// Generated by scripts/integrate-generated-media.mjs from visually accepted receipts.\nimport type { MediaItem } from './media.ts';\nexport const generatedMedia: Record<string, Partial<MediaItem>> = ${JSON.stringify(generated,null,2)};\n`);
fs.writeFileSync('public/media/generated/provenance.json',JSON.stringify(provenance,null,2)+'\n');
console.log(`Integrated ${Object.keys(generated).length}/${plan.length} reviewed images with ${Object.keys(generated).length*3} responsive WebP files.`);
