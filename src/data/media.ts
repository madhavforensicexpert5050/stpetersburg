/**
 * Customer-facing wording for illustrative images. Every label below switches to genuine wording on its own
 * once a slot holds an owner-licensed photo (rights: 'owner-licensed'), so captions never need hand edits.
 */
export const isIllustration = (m: Pick<MediaItem, 'rights'>) => m.rights !== 'owner-licensed';
export const isAiConcept = (m: Pick<MediaItem, 'rights'>) => m.rights === 'ai-generated';
export const anyIllustrations = () => media.some(isIllustration);
/** Lightbox title: the room or style name only, with no per-image disclosure line. */
export const zoomTitle = (_m: Pick<MediaItem, 'rights'>, name: string) => name;
/** Accessible name of the button that opens the lightbox */
export const zoomLabel = (m: Pick<MediaItem, 'rights'>, name: string) => (isIllustration(m) && !isAiConcept(m) ? `Enlarge illustration: ${name}` : `Enlarge image: ${name}`);

const byId = new Map(media.map((m) => [m.id, m]));
export function getMedia(id: string): MediaItem {
  const m = byId.get(id);
  if (!m) throw new Error(`Unknown media id: ${id}`);
  return m;
}
export function getPair(key: string): { before: MediaItem; after: MediaItem } {
  return { before: getMedia(`${key}-before`), after: getMedia(`${key}-after`) };
}
export const portfolioPairs = portfolioRooms.map(({ room, style }) => ({ key: `pf-${room}`, room, style }));

/** A real, integrated image. Placeholders never appear in the Portfolio. */
export const isApprovedMedia = (m: Pick<MediaItem, 'rights'>) => m.rights === 'ai-generated';
const pairReady = (key: string) => { const p = getPair(key); return isApprovedMedia(p.before) && isApprovedMedia(p.after); };

